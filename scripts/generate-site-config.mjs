import fs from 'node:fs';
const [repo, output] = process.argv.slice(2);
if (!/^[a-zA-Z0-9_.-]+\/[a-zA-Z0-9_.-]+$/.test(repo ?? '')) throw Error('Expected GitHub owner/repo');
if (!output || !output.endsWith('.js')) throw Error('Expected .js destination');
fs.writeFileSync(output, `/* Generated by GitHub Pages deployment; no credentials or user data. */\nwindow.SONTRIQA_REPOSITORY=${JSON.stringify(repo)};\n`, 'utf8');
console.log(`Generated site configuration for ${repo}`);
